void hub75_bcm_refresh_working(void)
{
    // We iterate through bit planes (0, 1, and 2)
    // For 8-bit color, you'd go 0 to 7.
    for (uint8_t bit = 0; bit < 3; bit++) 
    {
        // Calculate OE time: powers of 2 (1, 2, 4...)
        // Shift 1 by 'bit' to get 1, 2, 4. Multiply by base units.
        uint32_t on_time = (1 << bit) * 100; 

        for (uint8_t row = 0; row < ROW_PAIRS; row++)
        {
            // 1. Shift data for THIS specific bit plane
            for (int col = 0; col < PANEL_WIDTH; col++)
            {
                // Top Half: Check if the 'bit'-th bit is set
                if (my_image_R[row][col] & (1 << bit)) LED_PANEL_R1_Set(); else LED_PANEL_R1_Clear();
                if (my_image_G[row][col] & (1 << bit)) LED_PANEL_G1_Set(); else LED_PANEL_G1_Clear();
                if (my_image_B[row][col] & (1 << bit)) LED_PANEL_B1_Set(); else LED_PANEL_B1_Clear();

                // Bottom Half
                uint8_t row2 = row + ROW_PAIRS;
                if (my_image_R[row2][col] & (1 << bit)) LED_PANEL_R2_Set(); else LED_PANEL_R2_Clear();
                if (my_image_G[row2][col] & (1 << bit)) LED_PANEL_G2_Set(); else LED_PANEL_G2_Clear();
                if (my_image_B[row2][col] & (1 << bit)) LED_PANEL_B2_Set(); else LED_PANEL_B2_Clear();

                // CLK pulse
                GPIO_PA13_Set();
                delay_nops(1);
                GPIO_PA13_Clear();
            }

            // 2. Standard Latch Sequence
            LED_PANEL_OE_Set(); // Darken
            set_row(row);
            
            LED_PANEL_LAT_Set();
            delay_nops(2);
            LED_PANEL_LAT_Clear();

            // 3. Show for the calculated BCM duration
            LED_PANEL_OE_Clear();
            delay_nops(on_time);
            LED_PANEL_OE_Set();
        }
    }
}

